#!/usr/bin/env python3
"""Generate the per-class LaTeX tables from stored evaluation output.

Class names contain underscores and parentheses, so every cell is escaped rather
than trusted. A stray underscore is a LaTeX error, and a silently dropped one is
worse: it changes the class name in a table that is supposed to be a record.
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "thesis" / "generated"

ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def tex_escape(text: str) -> str:
    return "".join(ESCAPES.get(ch, ch) for ch in str(text))


def pretty(name: str) -> str:
    """Turn Corn_(maize)___Northern_Leaf_Blight into readable prose."""
    parts = name.split("___")
    crop = parts[0].replace("_", " ")
    crop = crop.replace("(maize)", "(maize)")
    disease = parts[1].replace("_", " ") if len(parts) > 1 else ""
    return f"{crop} --- {disease}" if disease else crop


def write_longtable(path: Path, rows, caption: str, label: str, note: str) -> None:
    lines = [
        r"% generated by scripts/make_thesis_tables.py -- do not edit",
        r"\begin{longtable}{@{}p{6.6cm}rrrr@{}}",
        rf"\caption{{{caption}}}\label{{{label}}}\\",
        r"\toprule",
        r"\textbf{Class} & \textbf{Precision} & \textbf{Recall} & \textbf{F1} & \textbf{Support}\\",
        r"\midrule",
        r"\endfirsthead",
        rf"\multicolumn{{5}}{{l}}{{\small\itshape {caption} (continued)}}\\",
        r"\toprule",
        r"\textbf{Class} & \textbf{Precision} & \textbf{Recall} & \textbf{F1} & \textbf{Support}\\",
        r"\midrule",
        r"\endhead",
        r"\midrule",
        rf"\multicolumn{{5}}{{r}}{{\small\itshape continued on next page}}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for r in rows:
        lines.append(
            f"{tex_escape(pretty(r['class']))} & {float(r['precision']):.3f} & "
            f"{float(r['recall']):.3f} & {float(r['f1']):.3f} & {int(float(r['support']))} \\\\"
        )
    lines += [r"\end{longtable}", "", note, ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  {path.name}: {len(rows)} rows")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    pv = ROOT / "reports/model_comparison/locked_test_efficientnet_b0/test/classification_report.csv"
    rows = sorted(csv.DictReader(open(pv, encoding="utf-8")), key=lambda r: -int(float(r["support"])))
    write_longtable(
        OUT / "per_class_plantvillage.tex", rows,
        "Per-class performance on the PlantVillage locked test (10,709 images)",
        "tab:perclasspv",
        r"\noindent{\small Classes ordered by support. Macro averages in Chapter~\ref{ch:results} "
        r"are the unweighted mean over these rows.}",
    )

    fd = ROOT / "reports/s19/_field/baseline_seed42/per_class.csv"
    rows = sorted(csv.DictReader(open(fd, encoding="utf-8")), key=lambda r: -int(float(r["support"])))
    write_longtable(
        OUT / "per_class_plantdoc.tex", rows,
        "Per-class performance on PlantDoc test (236 images, 27 classes)",
        "tab:perclasspd",
        r"\noindent{\small Cohort B baseline checkpoint. Precision is 0 for classes the model "
        r"never predicted, which is a real failure rather than a missing value.}",
    )


if __name__ == "__main__":
    main()
